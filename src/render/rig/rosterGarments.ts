export function drawRosterGarment(
  behind: Graphics,
  front: Graphics,
  at: Point,
  radius: number,
  style: RosterGarment,
  sway: number,
): void {
  const { edge, back, front: panels } = OUTFITS[style];
  const layer = (g: Graphics, entries: Panel[], drift: number) => {
    for (const [color, vertices] of entries) {
      const points = vertices.flatMap(([f, s, h]) => {
        const p = at(f, s + drift * Math.max(0, 1.1 - h), h);
        return [p.x, p.y];
      });
      g.poly(points)
        .fill({ color })
        .stroke({ color: edge, width: Math.max(0.8, radius * 0.065) });
    }
  };
  layer(behind, back, sway);
  layer(front, panels, 0);
  if (style === 'cleric') {
    const halo = at(0.45, 0, 2.33);
    front
      .ellipse(halo.x, halo.y, radius * 0.43, radius * 0.16)
      .stroke({ color: 0xf5cf88, width: Math.max(1, radius * 0.08) });
  }
}
