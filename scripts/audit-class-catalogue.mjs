/** Read-only, resolved catalogue inventory. Run from the repository root. */
import { createServer } from 'vite';
import { format } from 'prettier';
import { readFileSync, writeFileSync } from 'node:fs';

const server = await createServer({ server: { middlewareMode: true } });
try {
  const { World } = await server.ssrLoadModule('/src/engine/world/world.ts');
  const { CLASS_IDS, describeAbility } = await server.ssrLoadModule(
    '/src/engine/content/classes.ts',
  );
  const { ALL_SUBCLASSES } = await server.ssrLoadModule('/src/engine/content/subclasses.ts');
  const rows = [];
  const escape = (s) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
  const worldFor = (classId, subSkills = []) =>
    new World({
      monsterId: 'lich',
      seed: 31,
      players: [{ peerId: 'audit', name: 'Audit', classId, subSkills }],
    });
  const row = (id, ab) => `| ${id} | ${escape(ab.name)} | ${escape(describeAbility(ab))} |`;
  let bases = 0;
  let choices = 0;
  const passives = new Set();
  for (const id of CLASS_IDS) {
    rows.push(
      `## ${id}`,
      '',
      '| Slot / stable ID | Ability | Resolved unupgraded behavior |',
      '| --- | --- | --- |',
    );
    const p = worldFor(id).players[0];
    for (const [slot, ab] of Object.entries(p.abilities)) {
      rows.push(row(slot, ab));
      bases++;
    }
    for (const sub of ALL_SUBCLASSES.filter((s) => s.classId === id)) {
      rows.push(
        '',
        `### ${sub.name}`,
        '',
        sub.passive.desc,
        '',
        '| Stable ID | Ability | Resolved unupgraded behavior |',
        '| --- | --- | --- |',
      );
      for (const skill of sub.skills) {
        const owner = worldFor(id, [skill.id]).players[0];
        if (owner.subclassPassiveId !== sub.passive.id || !owner.subAbilities?.sub1)
          throw new Error(`Missing native binding/passive: ${skill.id}`);
        passives.add(owner.subclassPassiveId);
        rows.push(row(skill.id, owner.subAbilities.sub1));
        choices++;
      }
    }
    rows.push('');
  }
  if (CLASS_IDS.length !== 12 || bases !== 48 || choices !== 96 || passives.size !== 24)
    throw new Error(
      `Catalogue coverage changed: ${CLASS_IDS.length}/${bases}/${choices}/${passives.size}`,
    );
  const unformatted =
    '# Resolved class catalogue\n\nGenerated by `node scripts/audit-class-catalogue.mjs`; do not hand-edit.\n\n12 classes, 48 base slots, 96 subclass choices, 24 passives. Each subclass\nchoice is independently bound through a real World spawn. This verifies binding\nand resolves actual cooldowns; it does not prove practical combat balance or\nevery Forge/upgrade combination. Seed 31, authored definitions, no upgrades.\nSee [the audit](CLASS_COHERENCE_AUDIT.md) for assessment and proposed changes.\n\n' +
    rows.join('\n');
  const content = await format(unformatted, { parser: 'markdown' });
  const target = 'docs/CLASS_CATALOGUE.md';
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content)
      throw new Error('Catalogue is stale; regenerate it.');
  } else writeFileSync(target, content);
  console.log(
    `Verified 12 classes / ${bases} base slots / ${choices} subclass bindings / ${passives.size} passives.`,
  );

  if (process.argv.includes('--probe')) {
    const { onMoonAbility } = await server.ssrLoadModule('/src/engine/combat/moonForm.ts');
    const { tickBuffs } = await server.ssrLoadModule('/src/engine/combat/combat.ts');
    const { tickSubclassPassives } = await server.ssrLoadModule(
      '/src/engine/combat/subclassPassives.ts',
    );
    const probes = [];
    for (const maxHp of [140, 280])
      for (const damageMult of [1, 2]) {
        const w = worldFor('druid', ['dr_moon_maul']);
        w.scene = null;
        const p = w.players[0],
          boss = w.boss;
        p.pos = { x: 600, y: 400 };
        p.aim = { x: 1, y: 0 };
        p.maxHp = maxHp;
        p.hp = 1;
        p.damageMult = damageMult;
        boss.pos = { x: 660, y: 400 };
        boss.hp = boss.maxHp = 10000;
        boss.buffs = [];
        onMoonAbility(w, p, p.abilities.a2);
        // Binary-exact tick keeps sampling off floating-point gate boundaries.
        for (let tick = 0; tick < 48; tick++) {
          if (tick % 8 === 0) onMoonAbility(w, p, p.abilities.basic);
          tickBuffs(p, 0.125);
          tickSubclassPassives(p, 0.125);
        }
        const clawDamage = 10000 - boss.hp,
          mend = p.hp - 1;
        if (clawDamage !== 84 * damageMult || mend !== 24)
          throw new Error('Moon audit probe changed');
        probes.push({ maxHp, damageMult, clawDamage, mend });
      }
    console.table(probes);
  }
} finally {
  await server.close();
}
